#!/usr/bin/env python3
"""Black-hole accretion rate versus redshift for several SWIFT SPIN_JET runs.

For every snapshot of every run directory given, read the PartType5 (black
hole) arrays and compute population statistics (median / 90th percentile /
maximum over all BHs) of

  * the accretion rate  mdot  [Msun/yr]          (AccretionRates, after the
    Eddington cap and the accretion-efficiency suppression -- what the BH
    actually grows by),
  * the Eddington ratio f_Edd                     (EddingtonFractions, same
    stage as mdot),
  * the raw Eddington ratio f_Edd,raw             (UnsuppressedEddingtonFractions:
    Krumholz/Bondi x boost, BEFORE the cap and the efficiency suppression --
    the quantity that drives the LRD gate),
  * the BH subgrid mass  M_sub [Msun].

and plot them against redshift, one colour per run, plus a text table.

Only the small BH datasets are read, so this is cheap even for many large
snapshots (run it with `nice` on a login node, or inside a job).

Usage
-----
    python3 plot_accretion_history.py LRD_base LRD_base_free LRD_base_boost \
        --out-png accretion_vs_z.png --out-txt accretion_vs_z.txt
    python3 plot_accretion_history.py --stride 5 run1 run2      # every 5th snap

Requires: numpy, h5py, matplotlib.
"""

import argparse
import glob
import os
import re
import sys

import numpy as np

try:
    import h5py
except ImportError:
    sys.exit("This script needs h5py (pip install h5py).")

MSUN_CGS = 1.98841e33
YR_S = 3.15576e7

# Categorical slots 1-4 (fixed order, never cycled).
RUN_COLORS = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100"]


def _phys_cgs(dset):
    """Dataset -> physical CGS using SWIFT's unit attributes."""
    key = "Conversion factor to physical CGS (including cosmological corrections)"
    if key not in dset.attrs:
        raise KeyError(f"unit attribute missing on {dset.name}")
    return np.asarray(dset[:], dtype=float) * float(np.atleast_1d(dset.attrs[key])[0])


def _stats(x):
    """(median, p90, max) over finite values; NaNs if empty."""
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]
    if x.size == 0:
        return (np.nan, np.nan, np.nan)
    p50, p90 = np.percentile(x, [50, 90])
    return (p50, p90, x.max())


def snapshot_list(run_dir, stride):
    snaps = sorted(
        p for p in glob.glob(os.path.join(run_dir, "snap_*.hdf5"))
        if re.search(r"snap_\d+\.hdf5$", p)
    )
    if stride > 1 and snaps:
        # keep the last one so the final state is always shown
        snaps = snaps[::stride] + ([snaps[-1]] if (len(snaps) - 1) % stride else [])
    return snaps


def read_snapshot(path):
    with h5py.File(path, "r") as f:
        z = float(np.atleast_1d(f["Header"].attrs["Redshift"])[0])
        n_bh = int(np.atleast_1d(f["Header"].attrs["NumPart_Total"])[5])
        row = {"snap": os.path.basename(path), "z": z, "n_bh": n_bh}
        if n_bh == 0 or "PartType5" not in f:
            return row
        bh = f["PartType5"]
        mdot = _phys_cgs(bh["AccretionRates"]) / MSUN_CGS * YR_S
        msub = _phys_cgs(bh["SubgridMasses"]) / MSUN_CGS
        fedd = np.asarray(bh["EddingtonFractions"][:], dtype=float)
        fraw = (np.asarray(bh["UnsuppressedEddingtonFractions"][:], dtype=float)
                if "UnsuppressedEddingtonFractions" in bh else None)
        lrd = (np.asarray(bh["LRDConfinedFlags"][:]).astype(bool)
               if "LRDConfinedFlags" in bh else None)

    row["mdot"] = _stats(mdot)
    row["mdot_sum"] = float(np.nansum(mdot))
    row["fedd"] = _stats(fedd)
    row["fraw"] = _stats(fraw) if fraw is not None else (np.nan,) * 3
    row["msub"] = _stats(msub)
    row["n_lrd"] = int(lrd.sum()) if lrd is not None else -1
    return row


def process_run(run_dir, stride):
    rows = []
    snaps = snapshot_list(run_dir, stride)
    for i, p in enumerate(snaps):
        try:
            rows.append(read_snapshot(p))
        except (OSError, KeyError) as e:
            sys.stderr.write(f"  [skip] {p}: {e}\n")
        if (i + 1) % 25 == 0:
            sys.stderr.write(f"  {os.path.basename(run_dir)}: {i + 1}/{len(snaps)}\n")
    rows = [r for r in rows if r["n_bh"] > 0]
    rows.sort(key=lambda r: -r["z"])
    return rows


def write_table(results, out_txt):
    cols = ("snap", "z", "N_BH", "N_LRD",
            "mdot_p50", "mdot_p90", "mdot_max", "mdot_sum",
            "fEdd_p50", "fEdd_p90", "fEdd_max",
            "fraw_p50", "fraw_p90", "fraw_max",
            "Msub_p50", "Msub_max")
    with open(out_txt, "w") as fh:
        fh.write("# BH accretion history per snapshot (generated by "
                 "tools/LRD/plot_accretion_history.py)\n")
        fh.write("# mdot [Msun/yr] = AccretionRates (after Eddington cap and "
                 "accretion-efficiency suppression); mdot_sum = sum over all BHs\n")
        fh.write("# fEdd = EddingtonFractions (same stage as mdot); "
                 "fraw = UnsuppressedEddingtonFractions (Bondi/Krumholz x boost, "
                 "before cap and suppression; drives the LRD gate)\n")
        fh.write("# Msub [Msun] = SubgridMasses; p50/p90 = percentiles over all BHs; "
                 "N_LRD = BHs with LRDConfinedFlags=1 (-1: field absent)\n")
        for name, rows in results:
            fh.write(f"\n## run: {name}   ({len(rows)} snapshots with BHs)\n")
            fh.write("# " + " ".join(f"{c:>11s}" for c in cols) + "\n")
            for r in rows:
                vals = [r["snap"].replace("snap_", "").replace(".hdf5", ""),
                        f"{r['z']:.4f}", str(r["n_bh"]), str(r["n_lrd"])]
                vals += [f"{v:.4e}" for v in r["mdot"]] + [f"{r['mdot_sum']:.4e}"]
                vals += [f"{v:.4e}" for v in r["fedd"]]
                vals += [f"{v:.4e}" for v in r["fraw"]]
                vals += [f"{r['msub'][0]:.4e}", f"{r['msub'][2]:.4e}"]
                fh.write("  " + " ".join(f"{v:>11s}" for v in vals) + "\n")
    print(f"wrote {out_txt}")


def make_plot(results, out_png, lrd_threshold, title):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    from matplotlib.ticker import FixedLocator, NullFormatter, NullLocator

    plt.rcParams.update({
        "font.size": 9, "axes.edgecolor": "#8a8a85", "axes.linewidth": 0.8,
        "xtick.color": "#55554f", "ytick.color": "#55554f",
        "axes.labelcolor": "#2b2b28", "text.color": "#2b2b28",
    })
    fig, axes = plt.subplots(2, 2, figsize=(11, 8), sharex=True)
    panels = [
        ("mdot", r"$\dot M_{\rm BH}$ [M$_\odot$ yr$^{-1}$]",
         "(a) accretion rate (after cap & efficiency)"),
        ("fedd", r"$f_{\rm Edd}$", "(b) Eddington ratio (after cap & efficiency)"),
        ("fraw", r"$f_{\rm Edd,raw}$", "(c) raw Eddington ratio (Krumholz x boost, LRD gate)"),
        ("msub", r"$M_{\rm sub}$ [M$_\odot$]", "(d) BH subgrid mass"),
    ]

    zmax = 0.0
    for ax, (key, ylabel, ptitle) in zip(axes.flat, panels):
        for i, (name, rows) in enumerate(results):
            if not rows:
                continue
            c = RUN_COLORS[i % len(RUN_COLORS)]
            x = np.array([1.0 + r["z"] for r in rows])
            zmax = max(zmax, x.max())
            med = np.array([r[key][0] for r in rows])
            mx = np.array([r[key][2] for r in rows])
            pos = lambda a: np.where(a > 0, a, np.nan)  # log axis
            ax.plot(x, pos(med), color=c, lw=2, solid_capstyle="round")
            ax.plot(x, pos(mx), color=c, lw=1.2, ls="--")
            if len(rows) <= 10:  # short runs: show the snapshots
                ax.plot(x, pos(mx), "o", color=c, ms=4, mec="white", mew=1)
        if key in ("fedd", "fraw"):
            ax.axhline(1.0, color="#8a8a85", lw=0.8, ls=":")
            ax.text(0.99, 1.0, "Eddington", transform=ax.get_yaxis_transform(),
                    ha="right", va="bottom", fontsize=7, color="#55554f")
        if key == "fraw" and lrd_threshold is not None and lrd_threshold != 1.0:
            ax.axhline(lrd_threshold, color="#8a8a85", lw=0.8, ls="-.")
        ax.set_yscale("log")
        ax.set_xscale("log")
        ax.set_ylabel(ylabel)
        ax.set_title(ptitle, fontsize=9, loc="left")
        ax.grid(True, which="major", color="#e4e3df", lw=0.6)
        ax.set_axisbelow(True)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)

    # x axis: log(1+z), labelled in z
    zt = [z for z in (0, 1, 2, 3, 5, 7, 10, 14, 20) if 1 + z <= zmax * 1.05]
    for ax in axes.flat:
        ax.xaxis.set_major_locator(FixedLocator([1 + z for z in zt]))
        ax.xaxis.set_minor_locator(NullLocator())
        ax.xaxis.set_minor_formatter(NullFormatter())
        ax.set_xticklabels([str(z) for z in zt])
        ax.set_xlim(zmax * 1.05, 1.0)
    for ax in axes[1]:
        ax.set_xlabel("redshift z")

    handles = [Line2D([], [], color=RUN_COLORS[i % len(RUN_COLORS)], lw=2,
                      marker="o" if len(rows) <= 10 else None, ms=4,
                      label=name if len(rows) > 10 else
                      f"{name} ({len(rows)} snap with BHs)")
               for i, (name, rows) in enumerate(results)]
    handles += [Line2D([], [], color="#55554f", lw=2, label="median over BHs"),
                Line2D([], [], color="#55554f", lw=1.2, ls="--", label="maximum")]
    fig.legend(handles=handles, loc="upper center", ncol=len(handles),
               frameon=False, fontsize=8.5, bbox_to_anchor=(0.5, 0.995))
    if title:
        fig.suptitle(title, y=0.955, fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.93 if title else 0.96))
    fig.savefig(out_png, dpi=150)
    plt.close(fig)
    print(f"wrote {out_png}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("runs", nargs="+", help="run directories containing snap_*.hdf5")
    ap.add_argument("--labels", help="comma-separated labels (default: dir names)")
    ap.add_argument("--stride", type=int, default=1, help="use every N-th snapshot")
    ap.add_argument("--out-png", default="accretion_vs_z.png")
    ap.add_argument("--out-txt", default="accretion_vs_z.txt")
    ap.add_argument("--lrd-threshold", type=float, default=None,
                    help="mark this f_Edd,raw threshold in panel (c)")
    ap.add_argument("--title", default="")
    args = ap.parse_args(argv)

    labels = (args.labels.split(",") if args.labels
              else [os.path.basename(os.path.normpath(r)) for r in args.runs])
    if len(labels) != len(args.runs):
        sys.exit("--labels must have one entry per run")

    results = []
    for name, run in zip(labels, args.runs):
        sys.stderr.write(f"reading {run}\n")
        results.append((name, process_run(run, args.stride)))

    write_table(results, args.out_txt)
    make_plot(results, args.out_png, args.lrd_threshold, args.title)


if __name__ == "__main__":
    main()
